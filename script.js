let intermediateEliminatedNames = [];
const appMain = document.getElementById("app-main");

function renderApp() {
  if (!appMain) return;
  appMain.innerHTML = "";
  if (currentScreenIndex === -1) renderModeSelection();
  else if (currentScreenIndex < screens.length) renderQuestionScreen(screens[currentScreenIndex]);
  else if (currentScreenIndex === screens.length) { generateIntermediateCandidates(); renderIntermediateScreen(); }
  else renderFinalScreen();
}


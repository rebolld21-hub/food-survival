function renderQuestionScreen(screenData) {
  const wrapper = document.createElement('div');
  wrapper.className = 'screen active';
  wrapper.innerHTML = `<h2 class="question-title">${screenData.title}</h2>`;
  const controls = document.createElement('div');
  controls.className = 'options-grid';
  const categoryId = screenData.id.split('_')[1]; 
  let displayOptions = [...screenData.options];
  if (isGameMode) shuffleArray(displayOptions);
  const footer = document.createElement('div');
  footer.style.textAlign = "center";
  if (isGameMode) {
    const cd = document.createElement('div'); cd.className = 'game-count'; cd.id = 'game-count';
    footer.appendChild(cd);
  }
  const nextBtn = document.createElement('button');
  nextBtn.className = 'nav-btn btn-danger';
  nextBtn.innerText = currentScreenIndex === screens.length - 1 ? '候補を絞り込む！ 🔪' : '次へ 👉';
  const updateNextBtn = () => {
    if (isGameMode) {
      const needed = 5 - eliminated[categoryId].length;
      const el = document.getElementById('game-count');
      if (needed > 0) { nextBtn.disabled = true; if (el) el.innerText = `あと ${needed} 枚消してね！🃏`; }
      else { nextBtn.disabled = false; if (el) el.innerText = `準備OK！さらに消してもいいよ✨`; }
    }
  };
  displayOptions.forEach(opt => {
    const btn = document.createElement('button');
    btn.className = 'option-btn';
    if (isGameMode) btn.classList.add('card-back');
    if (eliminated[categoryId].includes(opt.label)) btn.classList.add('eliminated');
    btn.innerHTML = `<span>${opt.emoji} ${opt.label}</span>`;
    btn.onclick = () => {
      if (eliminated[categoryId].includes(opt.label)) return;
      if(navigator.vibrate) navigator.vibrate(50);
      eliminated[categoryId].push(opt.label);
      btn.classList.add('eliminated');
      updateNextBtn();
    };
    controls.appendChild(btn);
  });
  wrapper.appendChild(controls);
  nextBtn.onclick = () => { currentScreenIndex++; renderApp(); };
  footer.appendChild(nextBtn);
  wrapper.appendChild(footer);
  if (isGameMode) updateNextBtn();
  appMain.appendChild(wrapper);
}

function generateIntermediateCandidates() {
  let validFoods = allFoods.filter(food => {
    if (eliminated.genre.includes(food.genre)) return false;
    const isEliminatedType = food.type.some(t => eliminated.type.includes(t));
    if (isEliminatedType) return false;
    return true;
  });
  if (validFoods.length === 0) validFoods = [...allFoods];
  shuffleArray(validFoods);
  intermediateCandidates = validFoods.slice(0, 10);
  intermediateEliminatedNames = [];
}

